/**
 * Skill：一段**可复用的工作法**。
 *
 * 它和「人设」的区别：人设说「你是谁、什么性格」，skill 说「这件事按什么步骤做」。
 * 与「问答注入」的区别：问答是这一轮的事实（问过什么、答了什么），skill 是方法。
 *
 * skill 由**插件**提供（见 PluginEntry.skills）：插件是能力的载体，skill 是其中
 * 「不需要写代码的那部分」——一段可以直接进系统提示的工作法。插件关掉，skill 跟着
 * 一起消失（宿主按 enabled 过滤）。
 * @module @ryharness/server/plugins/skills
 */

/** 一条 skill：id、名字、一句话说明，以及正文（工作法本身）。 */
export interface SkillSpec {
  /** 稳定 id（跨插件唯一）。 */
  readonly id: string
  /** 展示名。 */
  readonly name: string
  /** 一句话说明：这套方法管什么事。 */
  readonly description: string
  /** 工作法正文：注入 agent 的系统提示。 */
  readonly body: string
  /**
   * 这套方法依赖的工具名。
   *
   * 方法与工具必须一起走：方法说"用 grill 问用户"，白名单里却没有 grill，模型
   * 就会把问题当普通文字复述出来——用户永远等不到问题卡，这一轮静静卡死，而且
   * **不报任何错**。所以工具名挂在方法上，装方法时一并放行。
   */
  readonly tools?: readonly string[]
}

/** 插件页里展示的一条 skill（多一个「谁提供的」）。 */
export interface SkillView extends SkillSpec {
  /** 提供它的插件 id。 */
  readonly pluginId: string
}

/** 盘问方法（grill me）的 skill id。 */
